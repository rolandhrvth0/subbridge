def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in STRINGS else "en"


def current_language() -> str:
    return _lang


def tr(key: str, **kw) -> str:
    s = STRINGS[_lang].get(key) or STRINGS["en"].get(key) or key
    return s.format(**kw) if kw else s
